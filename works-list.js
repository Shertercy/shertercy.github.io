/* ==========================================================================
   works-list.js  作品清单

   —— 这是你平时唯一需要改的文件 ——

   只有一条规则：
     有 path    → 是一个能打开的文档
     有 children → 是一层目录，里面还可以继续嵌

   分组、作品、章节，全都用这一条规则，想要多少层都行。

   新增一个能打开的文档，两步：
     1. 把 .txt 放进 作品/ 下面的某个文件夹
     2. 在下面找到位置，加一行 { name: '名字', path: '/作品/.../文件.txt' }

   加一行时注意（都要用英文符号）：
     - 上一行末尾要有逗号
     - 名字和路径用单引号包起来
     - path 必须以 / 开头，它从网站根目录算起
     - 某一层下面什么都没有时，侧边栏会自动不显示它

   日期（可选）：
     给一行加上 created 和 updated，正文上方就会显示出来。
     两个可以只写一个；都不写就什么都不显示。

       { name: '第一章', path: '/作品/主/test/1.txt',
         created: '2025-01-15', updated: '2025-02-03' }

     ★ 日期只能手填。浏览器读不到文件的创建时间，git 也不记录它。
       查日期的命令（在你仓库的目录里跑）：

         最后修改：
           git log -1 --format=%as -- "作品/主/test/1.txt"

         创建（最早那次提交）：
           git log --follow --format=%as -- "作品/主/test/1.txt" | tail -1

       填进 created 和 updated 就行。日期写成什么样子都可以，
       页面会原样显示，比如 '2025-01-15' 或 '2025年1月15日'。

   ★ 最容易犯的错：
     加一个新的作品时，忘了先把上一个作品的 } 和 , 补上。
     如果你改完之后侧边栏点不开了，八成就是这个——
     按 F12 打开控制台，第一行红色报错会指出大概在哪一行。
   ========================================================================== */

